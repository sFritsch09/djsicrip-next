// Every djsicrip file must have an entry above. An unmapped name is a bug,
// so fail loudly instead of falling back to another host.
export function djsicripFileUrl(item, field) {
  const stored = item[field];
  const key = BUCKET_KEYS[stored];
  if (!key) {
    throw new Error(`No S3 object mapped for djsicrip ${item.id}.${field}: ${stored}`);
  }
  return `${S3_DJSICRIP_URL}/${key}`;
}
